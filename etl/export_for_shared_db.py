r"""
Package the data the dashboards read for the university's PostgreSQL (the
`whva` database on psql.cs.uwindsor.ca), which our laptops cannot reach
directly: one compressed SQL file to copy to whva and load there with psql.

    .venv\Scripts\python.exe etl\export_for_shared_db.py

writes data/export/whva_warehouse.sql.gz with:
    - the whole `warehouse` schema (tables, views, indexes, data), and
    - public.windsor_shelter_cost_long, the one table outside it (Story 1's
      tenure chart), moved into `warehouse`: on PostgreSQL 15 ordinary users
      usually cannot create tables in `public`. The Story 1 build reads it
      from `warehouse` when SUPERSET_TARGET=shared.
    - read access for every user of the database, since Superset's
      connection logs in as its own user.

Loading it first drops our `warehouse` schema in that database, so a re-run
after a data refresh replaces everything cleanly; nothing outside it is
touched. On whva (see docs/deploy_university.md):

    gunzip -c whva_warehouse.sql.gz | psql -h psql.cs.uwindsor.ca -U patel3gc -d whva -v ON_ERROR_STOP=1 -1

Needs the project's PostgreSQL container running (pg_dump runs inside it).
"""

import gzip
import subprocess
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
OUTPUT = PROJECT_ROOT / "data" / "export" / "whva_warehouse.sql.gz"
CONTAINER = "windsor_housing_postgres"
DATABASE = "housing_windsor"
OUTSIDE_TABLE = "windsor_shelter_cost_long"

# Superset's connection to the university database (psql_ss_whva) logs in as
# its own database user, not ours, so it needs to read what we load. The data
# is public statistics, so every user of our `whva` database may read it.
FOOTER = """
GRANT USAGE ON SCHEMA warehouse TO PUBLIC;
GRANT SELECT ON ALL TABLES IN SCHEMA warehouse TO PUBLIC;
"""

HEADER = """-- Windsor Housing Analytics: the data the dashboards read.
-- Generated by etl/export_for_shared_db.py. Replaces the `warehouse` schema.
SET client_min_messages = warning;
DROP SCHEMA IF EXISTS warehouse CASCADE;
"""


def pg_dump(*args: str) -> str:
    cmd = ["docker", "exec", CONTAINER, "pg_dump", "-U", "postgres", "-d", DATABASE,
           "--no-owner", "--no-privileges", *args]
    return subprocess.run(cmd, check=True, capture_output=True, text=True, encoding="utf-8").stdout


def move_to_warehouse(sql: str) -> str:
    """public.windsor_shelter_cost_long -> warehouse.windsor_shelter_cost_long."""
    moved = sql.replace(f"public.{OUTSIDE_TABLE}", f"warehouse.{OUTSIDE_TABLE}")
    if f"public.{OUTSIDE_TABLE}" in moved or f"warehouse.{OUTSIDE_TABLE}" not in moved:
        raise ValueError("Could not move the Story 1 table into the warehouse schema")
    return moved


def build() -> str:
    return (HEADER + pg_dump("--schema=warehouse")
            + move_to_warehouse(pg_dump(f"--table=public.{OUTSIDE_TABLE}")) + FOOTER)


def main() -> None:
    sql = build()
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    with gzip.open(OUTPUT, "wt", encoding="utf-8") as fh:
        fh.write(sql)
    print(f"Wrote {OUTPUT} ({OUTPUT.stat().st_size / 1e6:.1f} MB compressed, {len(sql) / 1e6:.0f} MB of SQL)")


if __name__ == "__main__":
    main()
