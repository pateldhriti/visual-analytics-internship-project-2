"""
Audit the CMHC Windsor Rental Market Survey workbooks (editions 2019-2025)
and write docs/HISTORICAL_RENTAL_SOURCE_AUDIT.md. Read-only.

    .venv\\Scripts\\python.exe etl\\audit_rental_history_sources.py

Everything in the report is read from the workbooks at run time: sheet lists,
titles, header rows, zone and bedroom labels, footnotes, the Windsor CMA cells
for each candidate metric, and a comparison of every October that appears in
two consecutive editions (to expose revisions and the geography break).
"""

from __future__ import annotations

import datetime
import sys
from pathlib import Path

import openpyxl
from openpyxl.utils import get_column_letter

from cleaning_common import PROJECT_ROOT, RAW_DIR, normalize_text, parse_cmhc_rms_value, sha256_file
from clean_windsor_rental_history import (
    EDITIONS, METRICS, geography_basis, locate, read_cell, sheet_notes, sheet_title,
)

REPORT_PATH = PROJECT_ROOT / "docs" / "HISTORICAL_RENTAL_SOURCE_AUDIT.md"
ZONE_SHEET = "Table 1.1.1"
OTHER_TABLES = ["Table 1.1.5", "Table 1.1.9", "Table 3.1.7", "Table 3.1.8", "Table 3.1.9"]


def fmt(v) -> str:
    if v is None:
        return "—"
    if isinstance(v, float):
        return f"{v:,.0f}" if v.is_integer() else f"{v:,}"
    return str(v)


def table(header, rows) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c).replace("|", "\\|") for c in r) + " |" for r in rows]
    return out + [""]


def edition_profile(wb, edition: int) -> dict:
    ws = wb[ZONE_SHEET]
    loc = locate(ws, edition, "vacancy_rate")
    header = loc["header_row"]
    zones = []
    for r in range(header + 1, loc["row"] + 1):
        text = normalize_text(ws.cell(r, 1).value)
        if text:
            zones.append(text)
    bedrooms = [normalize_text(ws.cell(header - 1, c).value) for c in range(2, ws.max_column + 1)
                if normalize_text(ws.cell(header - 1, c).value)]
    sample = ws.cell(loc["row"], loc["columns"]["current"]["value_col"]).value
    geo_notes = sorted({n for m in METRICS.values() for n in sheet_notes(wb[m[0]]) if n.startswith("§")})
    return {"zones": zones, "bedrooms": bedrooms, "header_row": header, "cma_row": loc["row"],
            "value_type": type(sample).__name__, "geo_notes": geo_notes, "basis": geography_basis(wb, edition),
            "sheets": len(wb.sheetnames), "has_other": {t: t in wb.sheetnames for t in OTHER_TABLES}}


def main() -> int:
    raw_dir = RAW_DIR
    workbooks = {e: openpyxl.load_workbook(raw_dir / rel, data_only=True) for e, rel in EDITIONS.items()}
    profiles = {e: edition_profile(wb, e) for e, wb in workbooks.items()}
    cells = {(e, m, role): read_cell(wb[METRICS[m][0]], e, m, role)
             for e, wb in workbooks.items() for m in METRICS for role in ("previous", "current")}
    locs = {(e, m): locate(wb[METRICS[m][0]], e, m) for e, wb in workbooks.items() for m in METRICS}

    now = datetime.datetime.now().astimezone().strftime("%Y-%m-%d %H:%M %Z")
    L = [
        "# Historical Rental Source Audit — Windsor CMA, 2019–2025",
        "",
        f"Generated by `etl/audit_rental_history_sources.py` on {now}. Every value below is read from the",
        "workbooks at run time; nothing is typed in by hand. The workbooks are not modified.",
        "",
        "## Verdict",
        "",
        "| Indicator | Table | Bedroom | Retained | Comparability |",
        "|---|---|---|---|---|",
        "| Overall apartment vacancy rate | 1.1.1 | Total | **yes** | Same table, definition and layout in all 7 editions. "
        "Geography break 2022 (see below). |",
        "| Average 2-bedroom apartment rent | 1.1.2 | 2 Bedroom | **yes** | Same in all editions. Average of all surveyed "
        "units (not fixed sample), so year-to-year changes include composition effects. Geography break 2022. |",
        "| Apartment rental universe | 1.1.3 | Total | **yes, break-flagged** | Same table in all editions, but the 2022 "
        "geography change alone adds ~10% to the count: not comparable across the break. |",
        "| Apartment turnover rate | 1.1.6 | Total | **yes** | Same table, definition and layout in all editions. "
        "Geography break 2022. |",
        "",
        "**Geography break.** Editions 2023–2025 state that their data are based on the 2021 census geographic "
        "definitions, and the 2023 edition republished Oct-22 on that basis. Editions 2019–2022 carry no such note "
        "(earlier definitions, labelled `pre_2021_census`). 2022 is therefore kept twice in the history file, once "
        "per `geography_basis`; `is_primary_series` marks the 2021-census row for a continuous series. Within a "
        "basis the series are comparable; across the break they are not, most visibly for the universe.",
        "",
        "**Revisions.** Every October that appears in two consecutive editions was compared. The only differences "
        "are Oct-22 (2022 edition vs 2023 edition), i.e. the geography revision. See the overlap table.",
        "",
        "**Not used** (and why):",
        "",
        "- Zone-level series: zones were redefined (`Zone 6 - Remainder of CMA` → `Zone 6 - Remainder of CMA` + "
        "`Zone 7 - Essex` in 2023 → `Zone 6 - North Essex County` + `Zone 7 - South Essex County` from 2024).",
        "- Bachelor/studio detail: the label changed (`Bachelor` → `Studio`, 2025) and the CMA value is often "
        "suppressed.",
        "- Tables 1.1.9, 3.1.7, 3.1.8, 3.1.9: absent from the 2019 edition, so 2019–2025 coverage is impossible.",
        "- Table 1.1.5 (fixed-sample % change of rent): a change measure, not a level, and outside the priority "
        "list; left for a later decision.",
        "- Oct-18 (previous column of the 2019 edition): outside the requested 2019–2025 window.",
        "",
        "## Workbooks",
        "",
    ]
    L += table(["Edition", "Workbook", "Sheets", "SHA-256", "Header row", "Windsor CMA row (1.1.1)",
                "Cell storage", "Geography basis", "Geography footnote"],
               [(e, f"`data/raw/{EDITIONS[e]}`", p["sheets"], f"`{sha256_file(raw_dir / EDITIONS[e])[:12]}…`",
                 p["header_row"], p["cma_row"], p["value_type"], f"`{p['basis']}`", "; ".join(p["geo_notes"]) or "none")
                for e, p in profiles.items()])
    L += ["Cell storage: the 2019 edition stores numbers as numbers and writes the 'no significant change' trend "
          "marker as U+2212 (−); later editions store text such as `'1,027'` and use `-`. Both are handled.", ""]
    L += ["### Zones and bedroom groups (Table 1.1.1)", ""]
    L += table(["Edition", "Bedroom groups", "Zone rows (ending with the CMA row)"],
               [(e, ", ".join(p["bedrooms"]), "; ".join(p["zones"])) for e, p in profiles.items()])
    L += ["### Other tables present", ""]
    L += table(["Edition"] + OTHER_TABLES,
               [(e, *["yes" if p["has_other"][t] else "**no**" for t in OTHER_TABLES]) for e, p in profiles.items()])

    L += ["## Candidate metrics per edition (Windsor CMA row, apartment scope)", "",
          "Geography = the `Windsor CMA` row. Dwelling scope = private apartment structures (tables 1.x). "
          "Suppression marker in all editions: `**`. Reliability letters a/b/c/d; universe tables have none.", ""]
    for m, (sheet, prefix, bedroom, unit, _, _) in METRICS.items():
        L += [f"### `{m}` — {sheet}, bedroom `{bedroom}`, unit {unit}", ""]
        rows = []
        for e in EDITIONS:
            loc = locs[(e, m)]
            for role in ("previous", "current"):
                c = cells[(e, m, role)]
                rows.append((e, c["period_label"], role, f"`{c['source_cell']}`", c["raw_value"] if c["raw_value"] is not None else "—",
                             c["value_status"], c["reliability_code"] or "—", c["yoy_trend"] or "—",
                             f"`{get_column_letter(loc['group_start'])}:{get_column_letter(loc['group_end'])}`"))
        L += table(["Edition", "Period", "Column", "Source cell", "Raw", "Status", "Reliability", "Trend", "Group columns"], rows)
        titles = sorted({locs[(e, m)]["title"] for e in EDITIONS})
        L += ["Titles seen: " + " / ".join(f"`{t}`" for t in titles), ""]

    L += ["## Overlap check (same October in two consecutive editions)", ""]
    rows = []
    for e in list(EDITIONS)[1:]:
        for m in METRICS:
            prev = cells[(e, m, "previous")]
            older = cells[(e - 1, m, "current")]
            same = (prev["raw_value"] == older["raw_value"]) or (
                prev["value_status"] == older["value_status"] == "published"
                and parse_cmhc_rms_value(prev["raw_value"])[0] == parse_cmhc_rms_value(older["raw_value"])[0])
            rows.append((prev["period_label"], m, f"{e - 1}: {older['raw_value']}", f"{e}: {prev['raw_value']}",
                         "identical" if same else f"**differs** ({profiles[e - 1]['basis']} → {profiles[e]['basis']})"))
    L += table(["October", "Metric", "Earlier edition", "Later edition", "Result"], rows)

    REPORT_PATH.write_text("\n".join(L) + "\n", encoding="utf-8")
    for wb in workbooks.values():
        wb.close()
    print(f"Audit written: {REPORT_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
