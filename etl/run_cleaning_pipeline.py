def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--init-manifest", action="store_true",
                        help="record the raw-file baseline in etl/raw_manifest.json (only if it does not exist)")
    args = parser.parse_args()
    if args.init_manifest:
        if MANIFEST_PATH.exists():
            print(f"Manifest already exists, not overwriting: {MANIFEST_PATH}")
            return 1
        snap = write_manifest()
        print(f"Manifest written for {len(snap)} raw files: {MANIFEST_PATH}")
        return 0
    run()
    return 0


if __name__ == "__main__":
    sys.exit(main())
