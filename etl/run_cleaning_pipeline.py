"""
Rebuild all five cleaned staging files from the official raw files.

    .venv\\Scripts\\python.exe etl\\run_cleaning_pipeline.py

Steps:
  1. verify every raw file against etl/raw_manifest.json (SHA-256 + size)
  2. run the five cleaners (etl/clean_*.py) -> data/staging/
  3. verify the raw files again (proves nothing under data/raw/ was touched)
  4. write docs/DATA_CLEANING_REPORT.md from this run's actual counts

The manifest is the baseline for "raw files were not changed". It is created
once, from the files as downloaded, with:

    .venv\\Scripts\\python.exe etl\\run_cleaning_pipeline.py --init-manifest

and refuses to overwrite an existing manifest.
"""

